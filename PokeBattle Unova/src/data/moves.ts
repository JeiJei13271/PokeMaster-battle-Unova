/**
 * Tabla oficial de efectividad para los 8 tipos del prólogo de Teselia.
 * Cualquier combinación no listada vale 1.
 */
const CHART: Partial<Record<ElementType, Partial<Record<ElementType, number>>>> = {
  normal: { rock: 0.5 },
  fire: { grass: 2, fire: 0.5, water: 0.5, rock: 0.5 },
  water: { fire: 2, rock: 2, water: 0.5, grass: 0.5 },
  grass: { water: 2, rock: 2, fire: 0.5, grass: 0.5, flying: 0.5 },
  electric: { water: 2, flying: 2, grass: 0.5, electric: 0.5 },
  rock: { fire: 2, flying: 2 },
  dark: { dark: 0.5 },
  flying: { grass: 2, electric: 0.5, rock: 0.5 },
};

export function typeMultiplier(attack: ElementType, defenderTypes: ElementType[]): number {
  let mult = 1;
  for (const def of defenderTypes) {
    const row = CHART[attack];
    const value = row?.[def];
    if (value !== undefined) mult *= value;
  }
  return mult;
}
